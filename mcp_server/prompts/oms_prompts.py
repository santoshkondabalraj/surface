            f"- KG has EntityType nodes describing tables (columns, primary keys, etc.)\n"
            f"- Database has actual data in those tables\n"
            f"- To \"use YFS_ORGANIZATION table data\", query the database with SQL, not the KG\n\n"
            f"Process:\n"
            f"1. Query KG to learn the table schema (columns, types)\n"
            f"2. Build SQL query to query the actual database for data\n"
            f"3. Never try to MATCH against table names in KG: MATCH (org:YFS_ORGANIZATION) ❌\n\n"
            f"## Cypher Query Patterns (REFERENCE - Use these exactly)\n\n"
            f"Find a specific table:\n"
            f"```cypher\n"
            f"MATCH (e:EntityType) WHERE e.name = 'YFS_ORGANIZATION'\n"
            f"RETURN e.name, e.primary_key, e.columns, e.description\n"
            f"```\n\n"
            f"Find tables by pattern:\n"
            f"```cypher\n"
