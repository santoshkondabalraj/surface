            f"    - APPLY business rules from KG (e.g., ATP = QUANTITY_ONHAND - QUANTITY_RESERVED)\n"
            f"    - Add proper WHERE clauses for constraints\n"
            f"    - Example: WHERE ATP > 0 (from inventory rule), STATUS = '3350' (from business rule)\n\n"
            f"3d. EXECUTE SQL\n"
            f"    - Call execute_sql_query(sql_query)\n"
            f"    - Tool validates: read-only, safe, no dangerous keywords\n"
            f"    - Returns results\n\n"
            f"### STEP 4: Present Results\n\n"
            f"Show user:\n"
            f"- Data from API or SQL\n"
            f"- Source attribution (\"via getItemsByOrganization API\" or \"SQL query via database\")\n"
            f"- Any filters/constraints applied\n"
            f"- Row count\n\n"
            f"## ARCHITECTURE BOUNDARIES\n\n"
            f"| Source | Purpose | Tools |\n"
            f"|--------|---------|-------|\n"
            f"| Pinecone | Functional Capabilities (APIs, UEs, Events) | retrieve_skills |\n"
